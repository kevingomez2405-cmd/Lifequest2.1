CREATE TABLE MISIONES (
    ID_MISION INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE_MISION VARCHAR(100) NOT NULL,
    DESCRIPCION VARCHAR(255) NOT NULL,
    DIFICULTAD VARCHAR(20) NOT NULL,
    EXP_OTORGADA INT NOT NULL DEFAULT 0,
    MONEDAS_OTORGADAS INT NOT NULL DEFAULT 0,
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    FECHA_CREACION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FECHA_LIMITE DATETIME,
    FK_ID_META INT NOT NULL,
    FK_ID_PLANTILLA INT NOT NULL,
    FK_ID_ADMINISTRADOR INT NOT NULL,
    FK_ID_RECOMPENSA INT,
    CONSTRAINT CHK_DIFICULTAD_MISION CHECK (DIFICULTAD IN ('FACIL','MEDIA','DIFICIL')),
    CONSTRAINT CHK_ESTADO_MISION CHECK (ESTADO IN ('PENDIENTE','EN_PROGRESO','COMPLETADA','CANCELADA','VENCIDA')),
    CONSTRAINT CHK_EXP_OTORGADA CHECK (EXP_OTORGADA >= 0),
    CONSTRAINT CHK_MONEDAS_OTORGADAS CHECK (MONEDAS_OTORGADAS >= 0),
    CONSTRAINT CHK_FECHA_LIMITE CHECK (FECHA_LIMITE IS NULL OR FECHA_LIMITE >= FECHA_CREACION),
    CONSTRAINT FK_MISION_META
    FOREIGN KEY (FK_ID_META)REFERENCES META(ID_META)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
    CONSTRAINT FK_MISION_PLANTILLA
    FOREIGN KEY (FK_ID_PLANTILLA)REFERENCES PLANTILLA_MISION(ID_PLANTILLA)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    CONSTRAINT FK_MISION_ADMINISTRADOR
    FOREIGN KEY (FK_ID_ADMINISTRADOR)REFERENCES ADMINISTRADOR(ID_ADMINISTRADOR)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    CONSTRAINT FK_MISION_RECOMPENSA
    FOREIGN KEY (FK_ID_RECOMPENSA)REFERENCES RECOMPENSA(ID_RECOMPENSA)
    ON DELETE SET NULL
    ON UPDATE CASCADE);

CREATE TABLE PROGRESO (
    ID_PROGRESO INT AUTO_INCREMENT PRIMARY KEY,
    PORCENTAJE DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    INTENTOS INT DEFAULT 0,
    FECHA_INICIO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FECHA_ACTUALIZACION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    FECHA_FINALIZACION DATETIME NULL,
    FK_ID_USUARIO INT NOT NULL,
    FK_ID_MISION INT NOT NULL,
    CONSTRAINT UQ_PROGRESO_USUARIO_MISION UNIQUE (FK_ID_USUARIO, FK_ID_MISION),
    CONSTRAINT CHK_PORCENTAJE CHECK (PORCENTAJE BETWEEN 0 AND 100),
    CONSTRAINT CHK_ESTADO_PROGRESO CHECK (ESTADO IN ('PENDIENTE','EN_PROGRESO','COMPLETADA','CANCELADA')),
    CONSTRAINT FK_PROGRESO_USUARIO
    FOREIGN KEY (FK_ID_USUARIO)REFERENCES USUARIO(ID_USUARIO)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
    CONSTRAINT FK_PROGRESO_MISION
    FOREIGN KEY (FK_ID_MISION)REFERENCES MISIONES(ID_MISION)
    ON DELETE CASCADE
    ON UPDATE CASCADE);

